import crypto from 'node:crypto';
import { CreateTaskPayload, TaskPriority } from '../api/schemas/task.schema.js';

export class DataFactory {
  static uniqueId(prefix = 'qa'): string {
    return `${prefix}_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
  }

  static buildTask(overrides: Partial<CreateTaskPayload> = {}): CreateTaskPayload {
    const id = this.uniqueId('task');
    const priorities: TaskPriority[] = ['low', 'medium', 'high'];
    const priority = priorities[Math.floor(Math.random() * priorities.length)];

    return {
      title: `Automated Task ${id}`,
      description: `Generated by DataFactory (${id})`,
      priority,
      ...overrides,
    };
  }
}
